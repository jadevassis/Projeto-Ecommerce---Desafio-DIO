SELECT * FROM PRODUCT;

SELECT SELLER.SOCIALNAME AS VENDEDOR,
	   SELLER.CNPJ,
       SELLER.CPF,
       SELLER.LOCATION AS LOCALIZAÇÃO,
       PRODUCT.PNAME AS PRODUTO, 
       PRODUCTSELLER.PRODQUANTITY AS 'QUANTIDADE VENDIDA',
       CASE 
			WHEN PRODUCT.avaliação = 5 THEN 'EXCELENTE'
            WHEN PRODUCT.avaliação = 4 THEN 'OTIMO'
            WHEN PRODUCT.avaliação = 3 THEN 'BOM'
            WHEN PRODUCT.avaliação = 2 THEN 'RUIM'
            WHEN PRODUCT.avaliação = 1 THEN 'PESSIMO'
	    END AS 'Classificação de Venda'
	   FROM SELLER
		INNER JOIN PRODUCTSELLER ON IDSELLER
        INNER JOIN PRODUCT ON IDPRODUCT;

		


        
