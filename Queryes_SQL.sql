	   PRODUCTSTORAGE.QUANTITY AS QUANTIDADE,
       PRODUCT.PNAME AS PRODUTO,
       CASE 
			WHEN productStorage.QUANTITY >= 200 THEN 'ESTOQUE OK'
            WHEN productStorage.QUANTITY BETWEEN 100 AND 199 THEN 'ATENÇÃO'
            WHEN productStorage.QUANTITY <= 99 THEN 'ESTOQUE BAIXO'
	    END AS 'CLASSIFICAÇÃO DE ESTOQUE',
       SUPPLIER.SOCIALNAME AS FORNECEDOR,
       SUPPLIER.CNPJ
       FROM PRODUCTSTORAGE
		 INNER JOIN SUPPLIER ON IDSUPPLIER
         INNER JOIN PRODUCT ON IDPRODUCT;
         
