USE ECOMMERCE;

SHOW TABLES;

-- Produtos por clientes
SELECT * FROM CLIENTS;

SELECT CONCAT(CLIENTS.FNAME,' ', CLIENTS.LNAME) AS CLIENTE,
	   CLIENTS.ADDRESS AS ENDEREÇO,
       ORDERS.ORDERSTATUS AS STATUS,
       ORDERS.ORDERDESCRIPTION AS ORIGEM,
       PRODUCT.PNAME AS PRODUTO,
       SUM(PRODUCTORDER.POQUANTITY) AS TOTAL_ITEM
	   FROM CLIENTS
	  INNER JOIN ORDERS
		 ON CLIENTS.IDCLIENT
	  INNER JOIN PRODUCT 
		 ON IDPRODUCT
	  INNER JOIN PRODUCTORDER
		 ON IDPRODUCT
	  GROUP BY CLIENTE, ENDEREÇO, STATUS, ORIGEM, PRODUTO;
      
